"""
SafeSOC — Simulator Network Diagram
Renders the organisation as a Mermaid flowchart: internet -> edge
firewall -> core switch -> one subgraph per internal zone, with the
AWS account as its own subgraph. Generated from the YAML, so the
diagram in docs/simulator.md can't drift from the model.
"""

from __future__ import annotations

import re

from injector.sim.org import Org


def _node_id(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def _label(*lines: str) -> str:
    return '"' + "<br/>".join(line.replace('"', "'") for line in lines if line) + '"'


def mermaid(org: Org) -> str:
    edge_zones = [z for z in org.zones if z.subnet is None]
    internal = [z for z in org.zones if z.subnet is not None]
    edge_assets = [a for a in org.assets if a.zone in {z.name for z in edge_zones}]

    out = [
        "flowchart TB",
        f"    %% Generated by `python -m injector.sim org --diagram` from {org.name} (fictional).",
        f"    internet(({_label('Internet', 'WAN ' + org.public_ips.get('edge_wan', ''))}))",
    ]
    for asset in edge_assets:
        out.append(f"    {_node_id(asset.hostname)}[{_label(asset.hostname, f'{asset.os} {asset.os_version} | {asset.role}', 'LAN ' + asset.ip)}]")
        out.append(f"    internet --> {_node_id(asset.hostname)}")
    out.append(f"    core{{{{{_label('Core switch', 'VLAN trunk')}}}}}")
    for asset in edge_assets:
        out.append(f"    {_node_id(asset.hostname)} --> core")

    for zone in internal:
        title = f"{zone.name} | VLAN {zone.vlan} | {zone.subnet}"
        if not zone.monitored:
            title += " | collectors"
        out.append(f"    subgraph zone_{_node_id(zone.name)}[{_label(title)}]")
        for asset in (a for a in org.assets if a.zone == zone.name):
            nat = f"NAT {asset.public_ip}" if asset.public_ip else ""
            out.append(f"        {_node_id(asset.hostname)}[{_label(asset.hostname, asset.ip, asset.role, nat)}]")
        out.append("    end")
        out.append(f"    core --- zone_{_node_id(zone.name)}")

    cloud = org.cloud
    out.append(f"    subgraph cloud[{_label(f'AWS account {cloud.account_id} | {cloud.region}')}]")
    for bucket in cloud.s3_buckets:
        out.append(f"        s3_{_node_id(bucket.name)}[{_label('S3 ' + bucket.name, bucket.sensitivity)}]")
    for user in cloud.iam_users:
        out.append(f"        iam_{_node_id(user.name)}[{_label('IAM ' + user.name)}]")
    services = ", ".join(f"{name}: {value}" for name, value in cloud.services.items())
    out.append(f"        aws_services[{_label(services)}]")
    out.append("    end")
    out.append("    internet -.-> cloud")
    return "\n".join(out) + "\n"
