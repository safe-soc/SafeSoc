BENCHMARK_SCENARIOS_BY_ID: dict[str, BenchmarkScenario] = {s.id: s for s in BENCHMARK_SCENARIOS}


def get_scenario(scenario_id: str) -> Optional[BenchmarkScenario]:
    return BENCHMARK_SCENARIOS_BY_ID.get(scenario_id)


def validate_scenarios() -> None:
    """
    Fail fast if a scenario contradicts the autonomy policy it claims to
    measure. Called at import time (below), so a mis-declared scenario
    breaks immediately rather than silently producing a scorecard that
    grades against the wrong ground truth.

    Deliberately checks only what is knowable from static config — that
    declared automatic actions really are AUTOMATIC and declared
    approval actions really are APPROVAL_REQUIRED. Whether the playbook
    catalog actually contains those steps is checked in
    tests/test_benchmark_scenarios.py, which can afford the fuller
    cross-reference.
    """
    seen: set[str] = set()
    for scenario in BENCHMARK_SCENARIOS:
        if scenario.id in seen:
            raise ValueError(f"Duplicate benchmark scenario id: {scenario.id}")
        seen.add(scenario.id)

        for action_type in scenario.expected_automatic_actions:
            if classify(action_type) != AutonomyClass.AUTOMATIC:
                raise ValueError(
                    f"{scenario.id} lists {action_type.value} as automatic, but the policy classifies it "
                    f"{classify(action_type).value}."
                )
        for action_type in scenario.expected_approval_actions:
            if classify(action_type) != AutonomyClass.APPROVAL_REQUIRED:
                raise ValueError(
                    f"{scenario.id} lists {action_type.value} as approval-required, but the policy classifies it "
                    f"{classify(action_type).value}."
                )
        if scenario.expected_patterns and scenario.expected_incidents == 0:
            raise ValueError(f"{scenario.id} expects detection but zero incidents.")


validate_scenarios()
