"""
SafeSOC — Autonomous SOC Benchmark Scenarios
The evaluation suite's ground truth: what each attack simulation is
expected to produce as it travels the real pipeline (ingest ->
correlation -> incident -> SOAR). Static Python config, not a database
table, for the same reason core/soar_playbooks.py and
core/mitre_mapping.py are: this is code-reviewed reference data, the
same for every run, and a migration would be the wrong tool for
editing it. Benchmark RESULTS are likewise never persisted as tenant
data — the runner (benchmarks/) writes them to a report artifact.

Two rules this file follows strictly, because a benchmark that
disagrees with the implementation measures nothing:

  1. MITRE techniques are NEVER written here. They are derived from
     core/mitre_mapping.py via the detected pattern, so the benchmark
     reports the same technique the product itself reports.
  2. Expectations describe what the EXISTING detectors, playbook
     catalog, and autonomy policy already do — they were read off
     services/correlation.py's thresholds and core/soar_playbooks.py's
     triggers, not chosen to make a nicer-looking scorecard.
     tests/test_benchmark_scenarios.py enforces that: it re-derives
     every expectation from the real catalog and policy and fails if
     this file drifts from them.

Telemetry is generated by injector/injector.py's existing scenario
functions (referenced by name — see `injector_scenario`), never
reimplemented here; the backend has no import dependency on the
repo-root injector, so the name stays a plain string and the runner
resolves it.
"""

from dataclasses import dataclass, field
from typing import Optional

from app.core.enums import AutonomyClass, CorrelationPattern, SoarActionType
from app.core.mitre_mapping import get_mitre_technique
from app.core.soar_policy import classify


class TelemetryDegradation:
    """
    A named, deliberate mutilation of otherwise-normal telemetry, applied
    by the runner to the injector's generated events. Used to prove the
    pipeline survives partial observability — the Phase 3.5 guarantee —
    rather than only ever being measured on perfect input.

    NONE is the default: the events go in exactly as the injector built
    them.
    """

    NONE = "none"
    # Drop both IP fields, reproducing a sensor that reports who and
    # what but never where from — the exact shape that crashed
    # correlation before Phase 3.5.
    STRIP_IP_ADDRESSES = "strip_ip_addresses"


@dataclass(frozen=True)
class BenchmarkScenario:
    id: str
    name: str
    description: str
    attack_stage: str

    # Which injector/injector.py SCENARIOS entry generates this
    # scenario's telemetry. None means the scenario builds no telemetry
    # of its own (see TENANT_ISOLATION, which reuses another scenario
    # across two tenants).
    injector_scenario: Optional[str]
    degradation: str = TelemetryDegradation.NONE

    # What services/correlation.py's detectors should find. Empty means
    # "nothing should be detected" — a restraint test, not a gap.
    expected_patterns: tuple[CorrelationPattern, ...] = ()
    expected_incidents: int = 1

    # What core/soar_playbooks.py should match for those patterns.
    expected_playbooks: tuple[str, ...] = ()

    # Action-level expectations, split by how the autonomy policy
    # (core/soar_policy.py) classifies them. Declared explicitly rather
    # than derived, so the file states intent; the test module proves
    # the intent matches the policy.
    expected_automatic_actions: tuple[SoarActionType, ...] = ()
    expected_approval_actions: tuple[SoarActionType, ...] = ()
    # Actions expected NOT to be instantiated at all, because the
    # degraded telemetry above leaves their evidence unresolvable.
    expected_skipped_actions: tuple[SoarActionType, ...] = ()

    # Scenarios whose point is a property other than "did we detect it"
    # — the runner routes these to a dedicated check.
    tenant_isolation_check: bool = False

    notes: str = ""

    @property
    def mitre_techniques(self) -> tuple[str, ...]:
        """Derived from the product's own mapping — never authored here."""
        techniques: list[str] = []
        for pattern in self.expected_patterns:
            for technique_id in get_mitre_technique(pattern).technique_ids:
                if technique_id not in techniques:
                    techniques.append(technique_id)
        return tuple(techniques)

    @property
    def mitre_tactics(self) -> tuple[str, ...]:
        tactics: list[str] = []
        for pattern in self.expected_patterns:
            tactic = get_mitre_technique(pattern).tactic
            if tactic not in tactics:
                tactics.append(tactic)
        return tuple(tactics)

    @property
    def expects_detection(self) -> bool:
        return bool(self.expected_patterns)

    @property
    def all_expected_actions(self) -> tuple[SoarActionType, ...]:
        return self.expected_automatic_actions + self.expected_approval_actions


